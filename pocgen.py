#!/usr/bin/env python3
"""
pocgen -- emit a SELF-CONTAINED, THROWAWAY proof-of-concept verifier for a
single finding (typically a fingerprinted library@version with a known CVE).

The output is two files per finding:
  poc_<slug>.py        a standalone, stdlib-only script with a behavioral
                       verify-harness and a clearly-marked section for an LLM
                       (or you) to fill with the CVE-specific check.
  poc_<slug>.prompt.md the exact instruction to hand an LLM so it writes the
                       check() body for THIS advisory.

Design stance: this generates a *verifier*, not an autonomous exploit. The
script is read-only and refuses non-local targets unless you pass
--i-am-authorized, it is rate-limited, and it decides CONFIRMED/NOT by a
behavioral signal you can see -- never by trusting generated text. Review the
generated code before running it.
"""

import json
import os
import re
import sys
import urllib.request
from dataclasses import dataclass

# AI fill uses the Anthropic Messages API when ANTHROPIC_API_KEY is set.
LLM_MODEL = os.environ.get("PRODSCAN_LLM_MODEL", "claude-sonnet-5-5")

DEFAULT_BODY = (
    "    # TODO(ai): replace with the CVE-specific verification.\n"
    "    return {\"status\": \"INCONCLUSIVE\",\n"
    "            \"evidence\": \"run_check() not implemented yet\"}")


@dataclass
class PocSpec:
    target: str                 # base URL the PoC runs against
    library: str                # e.g. "@hotwired/turbo"
    version: str                # e.g. "7.0.0"
    advisory_id: str            # e.g. "GHSA-xxxx" / "CVE-2023-..."
    advisory_summary: str       # short text from the vuln DB
    endpoint: str = "/"         # where the library is used / asset URL
    aliases: tuple = ()


def slug(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")[:50]


POC_TEMPLATE = '''#!/usr/bin/env python3
"""
THROWAWAY PoC VERIFIER -- generated by pocgen. Review before running.

AUTHORIZED TESTING ONLY. Run only against a system you own or are explicitly
authorized to test. This script is read-only by default and refuses to run
against a non-local host unless you pass --i-am-authorized.

Finding under test:
  target   : {target}
  library  : {library}@{version}
  advisory : {advisory_id}  {aliases}
  summary  : {advisory_summary}
  endpoint : {endpoint}

How to use:
  1. Have an LLM (or you) fill in run_check() below using poc_{slug}.prompt.md.
  2. Review the generated logic -- never trust it blind.
  3. Run:  python3 {poc_name} --i-am-authorized
  Exit codes: 0 CONFIRMED vulnerable, 1 NOT confirmed, 2 could-not-test.
"""
import argparse, ssl, sys, time, urllib.request, urllib.error

TARGET   = "{target}"
ENDPOINT = "{endpoint}"
LIBRARY  = "{library}"
VERSION  = "{version}"
ADVISORY = "{advisory_id}"

def is_local(url):
    return any(h in url for h in ("localhost", "127.0.0.1", "[::1]",
                                  ".localhost", ".test"))

def http(method, path, body=None, headers=None, timeout=10):
    """Minimal, rate-limited HTTP helper (read-only by default)."""
    time.sleep(0.25)  # be gentle
    url = path if path.startswith("http") else TARGET.rstrip("/") + path
    ctx = ssl.create_default_context(); ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE
    data = body.encode() if isinstance(body, str) else body
    req = urllib.request.Request(url, data=data, method=method,
                                 headers=headers or {{}})
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as r:
            return r.status, dict(r.headers), r.read().decode("utf-8", "replace"), time.time()-t0
    except urllib.error.HTTPError as e:
        return e.code, dict(e.headers), e.read().decode("utf-8", "replace"), time.time()-t0
    except Exception as e:  # noqa: BLE001
        return 0, {{}}, "__ERROR__ %s" % e, time.time()-t0


def run_check():
    """
    === AI-FILL THIS FUNCTION (see poc_{slug}.prompt.md) ===

    Implement a behavioral check for {advisory_id} in {library}@{version}.
    Return a dict:
      {{"status": "CONFIRMED"|"NOT"|"INCONCLUSIVE",
        "evidence": "<the request/response signal that proves it>"}}

    Rules:
      - Read-only; no destructive or state-changing requests.
      - Decide by an observable signal (differential, timing, reflected
        marker, version gate) -- not by assuming the version is bad.
      - Use http(...) above. Keep it to a handful of requests.
    """
{check_body}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--i-am-authorized", action="store_true",
                    help="required for non-local targets")
    args = ap.parse_args()
    if not is_local(TARGET) and not args.i_am_authorized:
        print("Refusing: non-local target without --i-am-authorized.", file=sys.stderr)
        sys.exit(2)
    print("PoC %s -> %s  (%s@%s)" % (ADVISORY, TARGET, LIBRARY, VERSION))
    res = run_check()
    print("RESULT:", res["status"])
    print("EVIDENCE:", res["evidence"])
    sys.exit({{"CONFIRMED": 0, "NOT": 1}}.get(res["status"], 2))


if __name__ == "__main__":
    main()
'''

PROMPT_TEMPLATE = '''# PoC prompt — {advisory_id} in {library}@{version}

You are writing a **read-only verification** check for an AUTHORIZED security
test. Fill in the `run_check()` function of `poc_{slug}.py` only.

## Finding
- Target: `{target}`
- Library: `{library}@{version}`
- Advisory: `{advisory_id}` {aliases}
- Summary: {advisory_summary}
- Where the library is loaded: `{endpoint}`

## Task
Write `run_check()` so it decides whether THIS target is actually affected by
{advisory_id}, using the `http(method, path, body, headers)` helper already in
the file. Return:
```
{{"status": "CONFIRMED" | "NOT" | "INCONCLUSIVE", "evidence": "<proof>"}}
```

## Hard rules
1. **Read-only.** No state-changing requests, no writes, no destructive verbs.
2. **Decide by an observable signal** — a differential response, a timing
   delta, a reflected unique marker, or an explicit version/behavior gate —
   never by assuming the version string means it's vulnerable.
3. Keep it to a few requests; the helper already rate-limits.
4. If the vuln is purely client-side (e.g. a DOM-XSS sink in the library), and
   it can't be proven over plain HTTP, return INCONCLUSIVE and say what manual
   step (e.g. headless-browser DOM check) would confirm it.
5. Output only the `run_check()` body. The human will review before running.
'''


def fill_check_via_llm(spec: PocSpec):
    """Ask the Anthropic API to write the run_check() body for this advisory.
    Returns the (4-space-indented) Python body, or None if no key / on error."""
    key = os.environ.get("ANTHROPIC_API_KEY")
    if not key:
        return None
    prompt = (PROMPT_TEMPLATE.format(
        target=spec.target, library=spec.library, version=spec.version,
        advisory_id=spec.advisory_id or "(none)",
        advisory_summary=(spec.advisory_summary or ""),
        endpoint=spec.endpoint, aliases=", ".join(spec.aliases),
        slug=slug(spec.advisory_id or spec.library))
        + "\n\nReturn ONLY the Python statements that form the body of "
          "run_check() (no `def`, no markdown fences). A helper "
          "`http(method, path, body=None, headers=None)` returning "
          "`(status, headers, text, elapsed)` is available, plus TARGET, "
          "ENDPOINT, LIBRARY, VERSION. End by returning the result dict.")
    try:
        body = json.dumps({"model": LLM_MODEL, "max_tokens": 1500,
                           "messages": [{"role": "user", "content": prompt}]}).encode()
        req = urllib.request.Request(
            "https://api.anthropic.com/v1/messages", data=body,
            headers={"content-type": "application/json", "x-api-key": key,
                     "anthropic-version": "2023-06-01"})
        with urllib.request.urlopen(req, timeout=90) as r:
            data = json.loads(r.read())
        txt = "".join(b.get("text", "") for b in data.get("content", [])
                      if b.get("type") == "text").strip()
        txt = re.sub(r"^```[a-zA-Z]*\n|\n```$", "", txt).strip("\n")
        # ensure every non-blank line is indented at least 4 spaces
        out = []
        for ln in txt.splitlines():
            out.append(ln if (not ln.strip() or ln.startswith("    ")) else "    " + ln)
        return "\n".join(out) or None
    except Exception:  # noqa: BLE001
        return None


def emit_poc(spec: PocSpec, outdir="pocs", check_body=None):
    os.makedirs(outdir, exist_ok=True)
    name = "poc_" + slug(spec.advisory_id or (spec.library + spec.version))
    poc_name = name + ".py"
    fields = dict(target=spec.target, library=spec.library, version=spec.version,
                  advisory_id=spec.advisory_id or "(none)",
                  advisory_summary=(spec.advisory_summary or "").replace('"', "'"),
                  endpoint=spec.endpoint, aliases=", ".join(spec.aliases),
                  slug=slug(spec.advisory_id or spec.library), poc_name=poc_name,
                  check_body=check_body or DEFAULT_BODY)
    with open(os.path.join(outdir, poc_name), "w") as f:
        f.write(POC_TEMPLATE.format(**fields))
    with open(os.path.join(outdir, name + ".prompt.md"), "w") as f:
        f.write(PROMPT_TEMPLATE.format(**{k: v for k, v in fields.items()
                                          if k != "check_body"}))
    return os.path.join(outdir, poc_name), os.path.join(outdir, name + ".prompt.md")


def _demo():
    # Demonstration spec (hypothetical advisory) so you can see the output.
    spec = PocSpec(target="http://localhost:3000", library="jquery",
                   version="2.2.4", advisory_id="CVE-2020-11022",
                   advisory_summary="jQuery before 3.5.0: passing HTML from "
                   "untrusted sources to DOM-manipulation methods can execute "
                   "untrusted code.", endpoint="/assets/jquery.js",
                   aliases=("GHSA-gxr4-xjj5-5px2",))
    p, q = emit_poc(spec)
    print("wrote", p, "and", q)


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--demo":
        _demo()
    else:
        print("usage: pocgen.py --demo   (or import emit_poc / PocSpec)")
