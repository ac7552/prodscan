def emit_client_poc(spec: "PocSpec", outdir="pocs"):
    """Write a runnable client-side HTML harness for a known library CVE.
    Returns (html_path, {"vendored": bool, "cves": [...], "matched": cve|None}).
    Raises RuntimeError if the library/advisory isn't a client-side one we can
    demo, or if the library versions can't be vendored."""
    found = client_poc_for(spec)
    if not found:
        raise RuntimeError("no client-side PoC available for this finding")
    key, cfg, matched = found
    os.makedirs(outdir, exist_ok=True)
    vuln_ver = spec.version or "0"
    fixed_ver = cfg["fixed_version"]
    vuln_js = "%s-%s.min.js" % (key, vuln_ver)
    fixed_js = "%s-%s.min.js" % (key, fixed_ver)
    ok_v = _ensure_vendor(outdir, vuln_js, cfg["cdn"].format(v=vuln_ver))
    ok_f = _ensure_vendor(outdir, fixed_js, cfg["cdn"].format(v=fixed_ver))
    if not (ok_v and ok_f):
        raise RuntimeError("could not obtain %s %s / %s (need network or a "
                           "vendored copy)" % (cfg["label"], vuln_ver, fixed_ver))
    # Order advisories: the finding's CVE first, then the rest of the family.
    order = sorted(cfg["advisories"].items(),
                   key=lambda kv: (kv[0] != matched, kv[0]))
    payloads = [{"cve": cve, "finding": (cve == matched),
                 "mech": a["mech"], "s": a["payload"]} for cve, a in order]
    cve_list = ", ".join(cve for cve, _ in order)
    subtitle = "%s DOM-manipulation XSS · %s · runs entirely locally" % (
        cfg["label"], cve_list)
    html = CLIENT_POC_TEMPLATE
    for marker, val in (("__LABEL__", cfg["label"]), ("__SUBTITLE__", subtitle),
                        ("__VULN_VER__", vuln_ver), ("__FIXED_VER__", fixed_ver),
                        ("__API__", cfg["api"]), ("__VULN_JS__", "vendor/" + vuln_js),
                        ("__FIXED_JS__", "vendor/" + fixed_js),
                        ("__PAYLOADS_JSON__", json.dumps(payloads))):
        html = html.replace(marker, val)
    name = "poc_" + slug((matched or spec.advisory_id or key) + "_" + vuln_ver) + ".html"
    path = os.path.join(outdir, name)
    with open(path, "w") as f:
        f.write(html)
    return path, {"vendored": True, "cves": [c for c, _ in order], "matched": matched}


